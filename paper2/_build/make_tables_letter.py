def run_full_generator():
    spec = importlib.util.spec_from_file_location('make_tables_full', FULL/'make_tables.py')
    mt = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mt)
    mt.HERE = HERE                   # numbers.tex and tables/ are written here; SOURCES stay as registered there
    mt.main()
    return mt


def letter_table(mt):
    """tables/table_n4_letter.tex: the planar N = 4 comparison, one row per loop order."""
    res = mt.load('n4')
    sp = mt.sp

    def coeff(r):
        tex = mt.n4_tex(r['DE']).replace('\\frac', '\\tfrac')
        if r['status'].startswith('fixes'):
            tex += '\\,[' + mt.N4_NAMES[r['status'].split()[1]] + ']'
        else:
            assert r['status'] in ('PASS', 'normalisation'), r
        return tex

    def row(rows, L, kmax, kmin):
        rs = {r['k']: r for r in rows if r['L'] == L}
        assert set(rs) == set(range(kmin, kmax + 1)), (L, sorted(rs))
        return ',\\ '.join(coeff(rs[k]) for k in range(kmax, kmin - 1, -1))

    mhv, nmhv = res['three_to_three'], res['nmhv']
    loops = res['loops_compared']
    assert loops == 5 and {r['L'] for r in nmhv} == {1, 2, 3, 4}
    t = ['\\begin{table*}[t]', '\\centering', '\\small', '\\setlength{\\tabcolsep}{5pt}',
         '\\begin{tabular}{cp{0.9\\textwidth}}', '\\toprule',
         '$L$ & MHV: coefficients of $2\\pi i\\,\\ell^k$, $k=2L-1,\\dots,1$\\\\', '\\midrule']
    t += [f'{L} & ${row(mhv, L, 2*L - 1, 1)}$\\\\' for L in range(1, loops + 1)]
    t += ['\\midrule', '$L$ & NMHV: coefficients of $\\pi i\\,\\frac{1+w}{1+w^*}\\,\\ell^k$, $k=2L-2,\\dots,0$\\\\', '\\midrule']
    t += [f'{L} & ${row(nmhv, L, 2*L - 2, 0)}$\\\\' for L in range(1, 5)]
    t += ['\\bottomrule', '\\end{tabular}',
          '\\caption{Planar $\\mathcal N=4$: the coefficients of the powers of $\\ell=\\ln|\\delta_*|$ in the $L$-loop '
          'MHV amplitude $\\mathcal E^{(L)}$, eqs.~(3.17)--(3.21) of ref.~\\cite{Dixon:2016epj}, and in the next-to-MHV '
          'amplitude $\\rho^{(L)}$, eqs.~(D.14)--(D.17) of its erratum, in $3\\to3$ kinematics, against '
          'eqs.~(\\ref{eq:kernel}), (\\ref{eq:Fm}) and~(\\ref{eq:n4exp}) with $\\nu=0$ and $\\nu=2$. The one-loop '
          'coefficients define $C_1$ and $K$; a coefficient followed by a constant in brackets fixes that constant, '
          'and every other coefficient is a prediction. All agree.}',
          '\\label{tab:n4letter}', '\\end{table*}']
    (HERE/'tables'/'table_n4_letter.tex').write_text('\n'.join(t) + '\n')
    return len(mhv) + len(nmhv)


def keep_used_tables():
    """keep the tables the two documents input; adapt the captions of the Supplement's tables"""
    docs = {d: (HERE/f'{d}.tex').read_text() for d in ('letter', 'supplement')}
    used = {n for s in docs.values() for n in re.findall(r'\\input\{tables/(table_[a-z0-9_]+)\.tex\}', s)}
    present = {p.stem for p in (HERE/'tables').glob('table_*.tex')}
    assert used <= present, used - present
    for name in sorted(present - used):
        (HERE/'tables'/f'{name}.tex').unlink()
    for name in sorted(used - {'table_n4_letter'}):
        p = HERE/'tables'/f'{name}.tex'
        s = p.read_text()
        s = s.replace('(appendix~\\ref{', '(Sec.~\\ref{').replace('section~\\ref{', 'Sec.~\\ref{')
        p.write_text(s)
    return sorted(used)


def arxiv_number():
    m = re.search(r'\\newcommand\{\\arxivII\}\{([^}]*)\}', (HERE/'arxiv_numbers.tex').read_text())
    assert m, 'arxiv_numbers.tex must define \\arxivII'
    return m.group(1)


def cited(path):
    keys = set()
    for m in re.findall(r'\\cite\{([^}]*)\}', path.read_text()):
        keys |= {k.strip() for k in m.split(',')}
    return keys


def write_companion_bib(number):
    sm_only = sorted(cited(HERE/'supplement.tex') - cited(HERE/'letter.tex') - {'SM', 'PaperII'})
    refs = ', which includes Refs.~\\cite{' + ','.join(sm_only) + '}' if sm_only else ''
    (HERE/'companion.bib').write_text(
        '% generated by make_tables.py from arxiv_numbers.tex and the citations of the two documents; do not edit\n'
        '@misc{PaperII,\n'
        '    author = "Bhattacharya, Arunima",\n'
        f'    title = "{{{TITLE_II}}}",\n'
        f'    eprint = "{number}",\n'
        '    archivePrefix = "arXiv",\n'
        '    primaryClass = "hep-ph",\n'
        '    year = "2026"\n'
        '}\n\n'
        '@misc{SM,\n'
        f'    note = "{SM_TEXT}{refs}"\n'
        '}\n')
    return sm_only


