#!/usr/bin/env python3
# Writes letter_labels.tex: the numbers that the equations, figures and tables of the Letter carry, for
# the references from the Supplemental Material to the Letter (the macro \Lref in supplement.tex and in
# the tables it inputs). The numbers are read from letter.aux, so the Letter is compiled first;
# `make pdf` runs this script between the two documents. The file is kept under version control, so
# that the Supplement also compiles on its own.
#
#   python3 letter_labels.py
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent


def cited():
    """the labels of the Letter that the Supplement cites, in its text and in its tables"""
    text = re.sub(r'(?<!\\)%.*', '', (HERE/'supplement.tex').read_text())
    for name in re.findall(r'\\input\{(tables/[^}]*)\}', text):
        text += (HERE/name).read_text()
    return sorted(set(re.findall(r'\\Lref\{([^}]*)\}', text)))


def numbers():
    """label -> number, from the \\newlabel lines of letter.aux"""
    aux = HERE/'letter.aux'
    if not aux.exists():
        sys.exit('letter.aux not found: compile letter.tex first (make pdf does both)')
    return dict(re.findall(r'\\newlabel\{([^}]*)\}\{\{([^{}]*)\}', aux.read_text()))


if __name__ == '__main__':
    have, want = numbers(), cited()
    missing = [k for k in want if k not in have]
    if missing:
        sys.exit('the Supplement cites labels that the Letter does not define: ' + ', '.join(missing))
    lines = ['% generated by letter_labels.py from letter.aux; do not edit']
    lines += [f'\\LetterLabel{{{k}}}{{{have[k]}}}' for k in want]
    (HERE/'letter_labels.tex').write_text('\n'.join(lines) + '\n')
    print(f'letter_labels.tex: {len(want)} labels of the Letter cited by the Supplement')
