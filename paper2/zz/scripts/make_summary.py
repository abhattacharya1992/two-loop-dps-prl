#!/usr/bin/env python3
"""Tables of the gg -> ZZ test, written from results_zz.json (analyse_zz.py), the evaluated
points, the route-B comparison points and the logs of the checks. Nothing is typed by hand.

Usage: make_summary.py RESULTS_JSON POINTS_A POINTS_ROUTE_B LOGS OUT_MD

Writes OUT_MD (the tables at the end of the README) and, next to it, the same name with the
suffix .json: the scan settings, the largest deviations and the results of the cross-checks,
in the normalisation of the source (alpha_s/2pi per loop). The paper's make_tables.py reads
that file together with results_zz.json.
"""
import json
import pathlib
import re
import sys
from fractions import Fraction

import mpmath as mp

mp.mp.dps = 30
res = json.loads(pathlib.Path(sys.argv[1]).read_text())
pa, pb, logs, out = map(pathlib.Path, sys.argv[2:6])

LOG_HEL = ("++++", "++--", "----", "--++")       # one-loop logarithm c1 G
K_HEL = ("+-++", "+---", "-+++", "-+--")         # |dJz| = 2, one-loop constant K
NOLOG_HEL = ("++00", "--00", "+-+-", "-+-+")     # dJz = 0, constant and no logarithm


def C(v):
    return mp.mpc(mp.mpf(v[0]), mp.mpf(v[1]))


def xL(beta):
    """x = (1 + beta)/2 and L = ln[x(1 - x)], exactly (results_zz.json stores them as floats)"""
    b = Fraction(beta)
    x = (1 + mp.mpf(b.numerator) / b.denominator) / 2
    return x, mp.log(x * (1 - x))


def e(x, n=1):
    """Upper bound with one significant digit, e.g. 3e-08 -> '3 × 10⁻⁸'."""
    x = float(x)
    if x == 0:
        return "0"
    exp = int(mp.floor(mp.log10(x)))
    m = int(mp.ceil(x / 10**exp))
    if m == 10:
        m, exp = 1, exp + 1
    sup = str(exp).translate(str.maketrans("-0123456789", "⁻⁰¹²³⁴⁵⁶⁷⁸⁹"))
    return f"{m} × 10{sup}" if m != 1 else f"10{sup}"


def sup(k):
    return str(k).translate(str.maketrans("0123456789", "⁰¹²³⁴⁵⁶⁷⁸⁹"))


def scan_settings(points):
    """Velocities, delta = 10^-k and the working digits, read from the points themselves."""
    pts = [json.loads(p.read_text()) for p in sorted(points.glob("zz_*.json"))]
    betas = sorted({p["beta"] for p in pts}, key=Fraction)
    ks = sorted({p["delta_exp"] for p in pts})
    regular = {k: min(p["dps"] for p in pts if p["delta_exp"] == k) for k in ks}
    per = (regular[ks[-1]] - regular[ks[0]]) // (ks[-1] - ks[0])
    base = regular[ks[0]] - per * ks[0]
    assert all(regular[k] == base + per * k for k in ks), "working digits are not linear in k"
    assert all(any(p["beta"] == b and p["delta_exp"] == k and p["dps"] == regular[k] for p in pts)
               for b in betas for k in ks), "a velocity is missing a value of delta"
    controls = [{"beta": p["beta"], "delta_exp": p["delta_exp"], "extra_digits": p["dps"] - regular[p["delta_exp"]]}
                for p in pts if p["dps"] != regular[p["delta_exp"]]]
    # Li22 calls whose arguments, in the order of the code, violate |a| < 1, |ab| < 1 (ggvv.py)
    li22 = {"max_rate": max(p["li22_max_rate"] for p in pts), "bad_order": sum(p["li22_bad_order"] for p in pts)}
    return {"points": len(pts), "betas": betas, "delta_exponents": ks,
            "digits": {"base": base, "per_decade": per}, "controls": controls, "li22": li22}


def grab(name, pattern):
    """All matches of `pattern` in logs/NAME; the log must exist and contain at least one."""
    found = re.findall(pattern, (logs / name).read_text())
    assert found, f"logs/{name}: nothing matches {pattern!r}"
    return found


S = {"scan": scan_settings(pa)}
lines = ["# gg → ZZ: results of the forward test (generated by make_summary.py)", ""]
betas = sorted(res["betas"], key=lambda b: float(Fraction(b)))

# --- one loop
lines += ["## One loop", "",
          "| β | c₁(++++)/(−8πi x²) | c₁(++−−)/(−8πi (1−x)²) | K(+−++)/(−4πi x(1−x)) | K(++00)/(−8πi x(1−x)) |",
          "|---|---|---|---|---|"]
one_dev = vanish = nolog_c1 = 0.0
for b in betas:
    r = res["betas"][b]
    x, L = xL(b)
    h = r["hel"]
    vals = [C(h["++++"]["c1"]) / (-8j * mp.pi * x**2), C(h["++--"]["c1"]) / (-8j * mp.pi * (1 - x) ** 2),
            C(h["+-++"]["K"]) / (-4j * mp.pi * x * (1 - x)), C(h["++00"]["K"]) / (-8j * mp.pi * x * (1 - x))]
    lines.append(f"| {b} | " + " | ".join(f"1 + {e(abs(v - 1))}" if abs(v - 1) > 0 else "1" for v in vals) + " |")
    # the same closed forms for the parity images and the other three |dJz| = 2 amplitudes
    closed = {"++++": ("c1", x**2, 8), "----": ("c1", x**2, 8), "++--": ("c1", (1 - x) ** 2, 8),
              "--++": ("c1", (1 - x) ** 2, 8), "++00": ("K", x * (1 - x), 8), "--00": ("K", x * (1 - x), 8)}
    closed |= {hh: ("K", x * (1 - x), 4) for hh in K_HEL}
    for hh, (key, f, n) in closed.items():
        one_dev = max(one_dev, float(abs(abs(C(h[hh][key])) / (n * mp.pi * f) - 1)))
    # the other amplitudes with even dJz vanish in the forward limit: no constant, no logarithm
    big = max(max(abs(C(v["c1"])), abs(C(v["K"]))) for v in h.values())
    for hh, v in h.items():
        if v["dJz"] % 2 == 0 and hh not in closed and hh not in NOLOG_HEL:
            vanish = max(vanish, float(max(abs(C(v["c1"])), abs(C(v["K"]))) / big))
    # no one-loop logarithm in the |dJz| = 2 group with a constant and in ++00, +-+- and images
    for hh in K_HEL + NOLOG_HEL:
        nolog_c1 = max(nolog_c1, float(abs(C(h[hh]["c1"])) / big))


def odd_powers(points):
    """Effective power n in |M| ~ p_T^n between the two smallest deltas, for the amplitudes with
    odd dJz, over the velocities, the helicities and the three parts."""
    hel = {"+": 1, "-": -1, "0": 0}
    pts = [json.loads(p.read_text()) for p in sorted(points.glob("zz_*.json"))]
    out = []
    for b in betas:
        reg = sorted((p for p in pts if p["beta"] == b and p["dps"] == S["scan"]["digits"]["base"]
                      + S["scan"]["digits"]["per_decade"] * p["delta_exp"]), key=lambda p: p["delta_exp"])
        p1, p2 = reg[-2], reg[-1]
        for h in p2["M"]:
            l1, l2, l3, l4 = (hel[c] for c in h)
            if ((l1 - l2) - (l3 - l4)) % 2 == 0:
                continue
            for part in ("1l", "2l_CF", "2l_CA"):
                m1, m2 = abs(C(p1["M"][h][part])), abs(C(p2["M"][h][part]))
                out.append(float(mp.log(m2 / m1) / mp.log(mp.sqrt(mp.mpf(p2["pT2"]) / mp.mpf(p1["pT2"])))))
    return [min(out), max(out)]


odd = odd_powers(pa)
lines += ["", "Entries are 1 + (upper bound on the relative deviation). Of the other helicity amplitudes with",
          "ΔJ_z = 0 or ±2, −−00 equals ++00, +−+− and −+−+ have a constant and no logarithm. All other",
          f"amplitudes with even ΔJ_z vanish in the forward limit (constant and logarithmic coefficients below {e(vanish)}",
          f"of the largest), and those with odd ΔJ_z vanish like p_T up to logarithms: |M| ∝ p_Tⁿ between the two",
          f"smallest δ with n between {mp.nstr(mp.mpf(odd[0]), 2)} and {mp.nstr(mp.mpf(odd[1]), 2)}.", ""]
S["one_loop"] = {"closed_form_max_rel_dev": one_dev, "vanishing_max_rel": vanish, "no_log_c1_max_rel": nolog_c1,
                 "odd_dJz_effective_power": odd}

# --- two loops, logarithm
lines += ["## Two loops: amplitudes with a one-loop logarithm (++++, ++−−)", "",
          "| β | part | f₃/c₁ | prediction | deviation | f₂/c₁ | prediction | deviation | window shift (f₂) |",
          "|---|---|---|---|---|---|---|---|---|"]
worst_log = {"f3": 0.0, "f2": 0.0, "shift3": 0.0, "shift2": 0.0, "f2_lower_model": 0.0}
for b in betas:
    r = res["betas"][b]
    x, L = xL(b)
    pred = {"2l_CF": (mp.mpf(-4) / 3, -2 * L - 3), "2l_CA": (mp.mpf(2) / 3, 2 * L)}
    for part in ("2l_CF", "2l_CA"):
        d3m = d2m = s3m = s2m = lm = 0.0
        vals = None
        for h in LOG_HEL:
            hh = r["hel"][h]
            c1 = C(hh["c1"])
            f = [C(v) for v in hh[part]["f"]]
            fw = [C(v) for v in hh[part]["f_w1"]]
            fl = [C(v) for v in hh[part]["f_lower_model"]]
            p3, p2 = pred[part]
            d3m = max(d3m, float(abs(f[3] / c1 - p3)))
            d2m = max(d2m, float(abs(f[2] / c1 - p2)))
            s3m = max(s3m, float(abs(f[3] - fw[3]) / abs(c1)))
            s2m = max(s2m, float(abs(f[2] - fw[2]) / abs(c1)))
            lm = max(lm, float(abs(fl[2] / c1 - p2)))
            if h == "++++":
                vals = (f[3] / c1, f[2] / c1)
        for k, v in (("f3", d3m), ("f2", d2m), ("shift3", s3m), ("shift2", s2m), ("f2_lower_model", lm)):
            worst_log[k] = max(worst_log[k], v)
        name = "C_F" if part == "2l_CF" else "C_A"
        lines.append(f"| {b} | {name} | {mp.nstr(mp.re(vals[0]), 10)} | {mp.nstr(pred[part][0], 10)} | {e(d3m)} | "
                     f"{mp.nstr(mp.re(vals[1]), 10)} | {mp.nstr(pred[part][1], 10)} | {e(d2m)} | {e(s2m)} |")
lines += ["", "Predictions (units α_s/2π per loop, L = ln[x(1−x)]): C_F part −4/3 and −2L − 3, C_A part",
          "2/3 and 2L. Deviations are the largest over ++++, ++−−, −−−− and −−++. With a quadratic instead",
          f"of a cubic in G in the p_T² term the deviations of f₂/c₁ grow to {e(worst_log['f2_lower_model'])}.", ""]

# --- two loops, constant
lines += ["## Two loops: amplitudes with |ΔJ_z| = 2 and a one-loop constant K (+−++, +−−−, −+++, −+−−)", "",
          "| β | part | f₂/K | prediction | deviation | f₁/K | prediction | deviation | window shift (f₁) | f₃/K |",
          "|---|---|---|---|---|---|---|---|---|---|"]
worst_K = {"f3": 0.0, "f2": 0.0, "f1": 0.0, "shift3": 0.0, "shift2": 0.0, "shift1": 0.0}
for b in betas:
    r = res["betas"][b]
    x, L = xL(b)
    pred = {"2l_CF": (mp.mpf(-4), -4 * L - 2), "2l_CA": (mp.mpf(2), 4 * L - 2)}
    for part in ("2l_CF", "2l_CA"):
        d = {k: 0.0 for k in worst_K}
        vals = None
        for h in K_HEL:
            hh = r["hel"][h]
            K = C(hh["K"])
            f = [C(v) for v in hh[part]["f"]]
            fw = [C(v) for v in hh[part]["f_w1"]]
            p2, p1 = pred[part]
            d["f3"] = max(d["f3"], float(abs(f[3] / K)))
            d["f2"] = max(d["f2"], float(abs(f[2] / K - p2)))
            d["f1"] = max(d["f1"], float(abs(f[1] / K - p1)))
            for j in (3, 2, 1):
                d[f"shift{j}"] = max(d[f"shift{j}"], float(abs(f[j] - fw[j]) / abs(K)))
            if h == "+-++":
                vals = (f[2] / K, f[1] / K)
        for k, v in d.items():
            worst_K[k] = max(worst_K[k], v)
        name = "C_F" if part == "2l_CF" else "C_A"
        lines.append(f"| {b} | {name} | {mp.nstr(mp.re(vals[0]), 12)} | {mp.nstr(pred[part][0], 12)} | {e(d['f2'])} | "
                     f"{mp.nstr(mp.re(vals[1]), 12)} | {mp.nstr(pred[part][1], 12)} | {e(d['f1'])} | {e(d['shift1'])} | {e(d['f3'])} |")
lines += ["", "Predictions: C_F part −4 and −4L − 2, C_A part 2 and 4L − 2; no cubic logarithm.", ""]
S["worst_log"], S["worst_K"] = worst_log, worst_K

# --- no logarithm expected
lines += ["## Two loops: ΔJ_z = 0 without a one-loop logarithm (++00, +−+−)", "",
          "| β | helicity | largest absolute values of f₃/K, f₂/K, f₁/K over C_F and C_A |", "|---|---|---|"]
nolog = 0.0
for b in betas:
    r = res["betas"][b]
    for h in NOLOG_HEL:
        hh = r["hel"][h]
        K = C(hh["K"])
        m = [max(float(abs(C(hh[p]["f"][j]) / K)) for p in ("2l_CF", "2l_CA")) for j in (3, 2, 1)]
        nolog = max(nolog, *m)
        if h in ("++00", "+-+-"):
            lines.append(f"| {b} | {h} | {e(m[0])}, {e(m[1])}, {e(m[2])} |")
lines += ["", f"Including −−00 and −+−+, all these coefficients are below {e(nolog)} |K|.", ""]
S["no_log_max"] = nolog

# --- precision control
lines += ["## Precision", ""]
for c in res["control"]:
    lines.append(f"- β = {c['beta']}, δ = 10⁻{sup(c['delta_exp'])}: {c['dps']} instead of {c['base_dps']} digits changes the "
                 f"amplitudes by at most (relative) " + ", ".join(f"{e(v)} ({k})" for k, v in c["max_rel_diff"].items()) + ".")
    for s in S["scan"]["controls"]:
        if (s["beta"], s["delta_exp"]) == (c["beta"], c["delta_exp"]):
            s["max_rel_diff"] = max(c["max_rel_diff"].values())
assert all("max_rel_diff" in s for s in S["scan"]["controls"])
lines.append("")

# --- checks of the evaluation (logs of make checks)
tensor = max(float(v) for v in grab("check_tensors.log", r"max \|B_file - B_candidate\| / max \|B\| = (\S+)"))
li = {tuple(map(int, m)) for m in grab("check_li22_order.log",
                                        r"(\d+) Li22 calls; convergent as given: (\d+); convergent if swapped: (\d+)")}
assert len(li) == 1, "the Li22 counts differ between the points of the check"
(calls, given, swapped), = li
one_bench = grab("crosscheck_1l_benchmark.log", r"(A\d+)_A_1l_qT: .* rel\. diff (\S+)")
two_bench = {name: re.findall(r"(A\d+)_A_2l_qT (2l_C[AF]): .* rel\. diff (\S+)", (logs / name).read_text())
             for name in ("crosscheck_2l_benchmark.log", "crosscheck_2l_benchmark_x12.log")}
assert all(two_bench.values()), "two-loop benchmark logs incomplete"
cf_bench = [(a, float(v)) for m in two_bench.values() for a, p, v in m if p == "2l_CF"]
ca_bench = [(a, float(v)) for m in two_bench.values() for a, p, v in m if p == "2l_CA"]
assert ca_bench and max(v for a,v in ca_bench)<=1e-20, 'the FORM CA comparison does not agree'
cf_where = {"benchmark": [a for a, p, v in two_bench["crosscheck_2l_benchmark.log"] if p == "2l_CF"],
            "t_u_exchanged": [a for a, p, v in two_bench["crosscheck_2l_benchmark_x12.log"] if p == "2l_CF"]}
cxx = grab("check_cxx.log", r"(benchmark point|beta = (\S+), delta = 10\^-(\d+)): largest relative difference "
                            r"between the Python translation and the compiled C\+\+ code: 1l (\S+), 2l_CF (\S+), 2l_CA (\S+)")
cxx_points = [dict({"point": "benchmark"} if lab == "benchmark point" else {"beta": b, "delta_exp": int(k)},
                   max_rel_diff={"1l": float(v1), "2l_CF": float(vf), "2l_CA": float(va)})
              for lab, b, k, v1, vf, va in cxx]
cxx_max = {p: max(float(m[3 + i]) for m in cxx) for i, p in enumerate(("1l", "2l_CF", "2l_CA"))}
liv = grab("check_li22_values.log", r"(benchmark point|beta = (\S+), delta = 10\^-(\d+)): (\d+) distinct arguments, "
                                    r"max\(\|a\|, \|ab\|\) up to (\S+); largest relative difference from the reference: (\S+)")
liv_points = [{"point": "benchmark"} if lab == "benchmark point" else {"beta": b, "delta_exp": int(k)}
              for lab, b, k, *_ in liv]
p2 = grab("check_p0002.log", r"p0002\.cpp: (\d+) statements \((.*?)\); p0002\.py: (\d+) statements; "
                              r"statements that differ: (\d+)")
(p2_cpp, p2_kinds, p2_py, p2_bad), = p2
lines += ["## Checks of the evaluation (from logs/)", "",
          f"- Tensor basis: the inverse of M_ik = T_i†·T_k equals the projectors of gg_projectors-1.0.inc to {e(tensor)}.",
          f"- Li₂,₂: {given} of the {calls} calls converge with the arguments as given, {swapped} with them exchanged.",
          f"- Benchmark point, one loop: all {len(one_bench)} coefficients agree between routes A and B to "
          f"{e(max(float(v) for a, v in one_bench))}.",
          f"- Benchmark point, two loops, C_F part ({', '.join(a for a, v in cf_bench)}): routes A and B agree to "
          f"{e(max(v for a, v in cf_bench))}.",
          f"- Benchmark point, two loops, C_A part (same coefficients): routes A and B agree to "
          f"{e(max(v for a,v in ca_bench))}.",
          f"- Compiled C++ code (algebraic part, quad precision) against the Python translation, nine coefficients, at "
          f"{len(cxx)} points: largest relative difference {e(cxx_max['1l'])} (one loop), {e(cxx_max['2l_CF'])} (C_F), "
          f"{e(cxx_max['2l_CA'])} (C_A).",
          f"- Li₂,₂ against an independent integral representation, for all arguments at {len(liv)} points "
          f"({sum(int(m[3]) for m in liv)} in total): largest relative difference {e(max(float(m[5]) for m in liv))}.",
          f"- p0002.cpp against the translated p0002.py, statement by statement: {p2_cpp} statements ({p2_kinds}), "
          f"{p2_bad} differ.", ""]
S["checks"] = {"tensor_basis_max_rel_diff": tensor,
               "li22": {"calls": calls, "convergent_as_given": given, "convergent_if_swapped": swapped},
               "benchmark_one_loop": {"coefficients": len(one_bench), "max_rel_diff": max(float(v) for a, v in one_bench)},
               "benchmark_two_loop_CF": {"coefficients": [a for a, v in cf_bench], **cf_where,
                                         "max_rel_diff": max(v for a, v in cf_bench)},
               "benchmark_two_loop_CA": {"coefficients": [a for a, v in ca_bench], "min_rel_diff": min(v for a, v in ca_bench),
                                         "max_rel_diff": max(v for a, v in ca_bench)},
               "cxx": {"points": cxx_points, "max_rel_diff": cxx_max},
               "li22_values": {"points": liv_points, "arguments": sum(int(m[3]) for m in liv),
                               "max_rate": max(float(m[4]) for m in liv), "max_rel_diff": max(float(m[5]) for m in liv)},
               "p0002": {"statements": int(p2_cpp), "statements_py": int(p2_py), "differ": int(p2_bad)}}

# --- route B on the forward line
lines += ["## The FORM file of finite remainders on the forward line (route B)", ""]


def load(p):
    return json.loads(p.read_text())


def route_a_point(rb):
    cand = sorted(pa.glob(f"zz_b{rb['beta'].replace('/', 'o')}_d{rb['delta_exp']}_p*.json"))
    cand = [c for c in cand if load(c)["dps"] == S["scan"]["digits"]["base"] + S["scan"]["digits"]["per_decade"] * rb["delta_exp"]]
    return load(cand[0]) if cand else None


cf_rows, ca_rows, ca_agreement = [], [], []
for f in sorted(pb.glob("zzB_*.json")):
    rb = load(f)
    ra = route_a_point(rb)
    k = rb["delta_exp"]
    if "2l_CF" in rb["parts"] and ra:
        n = [h for h in ra["M"] if abs(C(ra["M"][h]["2l_CF"])) > 0]
        worst = max(float(abs(C(ra["M"][h]["2l_CF"]) - C(rb["M"][h]["2l_CF"])) / abs(C(ra["M"][h]["2l_CF"]))) for h in n)
        cf_rows.append({"beta": rb["beta"], "delta_exp": k, "dps": rb["dps"], "amplitudes": len(n), "max_rel_diff": worst})
        lines.append(f"- C_F part, β = {rb['beta']}, δ = 10⁻{sup(k)}, all {len(n)} helicity amplitudes ({rb['dps']} digits): "
                     f"routes A and B agree to {e(worst)}.")
    if "2l_CA" in rb["parts"]:
        if ra:
            n=[h for h in ra['M'] if abs(C(ra['M'][h]['2l_CA']))>0]
            worst=max(float(abs(C(ra['M'][h]['2l_CA'])-C(rb['M'][h]['2l_CA']))/
                            abs(C(ra['M'][h]['2l_CA']))) for h in n)
            assert worst<1e-15, 'the forward FORM CA amplitudes do not agree'
            ca_agreement.append({'beta':rb['beta'],'delta_exp':k,'dps':rb['dps'],
                                 'amplitudes':len(n),'max_rel_diff':worst})
            lines.append(f"- C_A part, β = {rb['beta']}, δ = 10⁻{sup(k)}, all {len(n)} helicity amplitudes "
                         f"({rb['dps']} digits): routes A and B agree to {e(worst)}.")
        p2 = mp.mpf(rb["pT2"])
        vb = abs(C(rb["M"]["++++"]["2l_CA"]))
        va = abs(C(ra["M"]["++++"]["2l_CA"])) if ra else None
        ca_rows.append({"beta": rb["beta"], "delta_exp": k, "dps": rb["dps"], "abs_route_A": float(va) if ra else None,
                        "abs_route_B": float(vb), "pT2_abs_route_B": float(p2 * vb)})
lines.append("")
if ca_rows:
    lines += ["C_A part of the two-loop ++++ amplitude, |M|, from the C++ code (route A) and from",
              "gg_Aj_A_qT-1.0.inc (route B), and p_T²|M| of route B:", "",
              "| β | δ | route A | route B | p_T² × route B |", "|---|---|---|---|---|"]
    lines += [f"| {c['beta']} | 10⁻{sup(c['delta_exp'])} | {mp.nstr(mp.mpf(c['abs_route_A']), 6) if c['abs_route_A'] else '–'} | "
              f"{mp.nstr(mp.mpf(c['abs_route_B']), 6)} | {mp.nstr(mp.mpf(c['pT2_abs_route_B']), 3)} |" for c in ca_rows] + [""]
S["route_b_forward"] = {"CF": cf_rows, "CA": ca_agreement, "CA_plus4": ca_rows}

out.write_text("\n".join(lines) + "\n")
out.with_suffix(".json").write_text(json.dumps(S, indent=1) + "\n")
print("\n".join(lines))
